export function seedAgents(homePosition: (projectId: string) => [number, number]): Agent[] {
  return seeds.map(({ task, queue, ...a }) => {
    const currentTask: AgentTask | null = task
      ? {
          id: `t-${a.id}-0`,
          title: task.title,
          projectId: task.projectId === CITADEL_ID ? null : task.projectId,
          missionId: task.missionId ?? null,
          state: task.state,
          progress: task.progress,
          startedAt: ago(task.startedMinAgo),
          priority: task.priority ?? 'normal',
        }
      : null;
    const taskQueue: AgentTask[] = (queue ?? []).map((q, i) => ({
      id: `t-${a.id}-q${i}`,
      title: q.title,
      projectId: q.projectId,
      state: q.state,
      progress: 0,
      startedAt: 0,
      priority: 'normal',
    }));
    return {
      ...a,
      state: a.state as AgentState,
      currentTask,
      taskQueue,
      conversationIds: [],
      activitySource: currentTask || a.state === 'waiting' ? 'simulated' : null,
      // SCOUT starts at home so the demo shows it crossing the world.
      position: homePosition(a.homeProjectId),
      lastActivityAt: ago(2),
      squadId: null,
      waitingFor: a.waitingFor ?? null,
      blockedReason: null,
    };
  });
}
